export const translations: Record<Locale, Translations> = {
  en,
  ms,
  "zh-CN": zhCN,
  yue,
  ta,
};

type StringKeyOf<T> = Extract<keyof T, string>;
type DotPath<T> = {
  [K in StringKeyOf<T>]: T[K] extends string
    ? K
    : T[K] extends Record<string, unknown>
      ? `${K}.${DotPath<T[K]>}`
      : never;
}[StringKeyOf<T>];

export type TranslationKey = DotPath<Translations>;
export type TranslationValues = Record<string, string | number>;

function readPath(dictionary: Translations, path: TranslationKey): string | undefined {
  let node: unknown = dictionary;
  for (const part of path.split(".")) {
    if (!node || typeof node !== "object" || !(part in node)) return undefined;
    node = (node as Record<string, unknown>)[part];
  }
  return typeof node === "string" ? node : undefined;
}

export function translate(
  locale: Locale,
  key: TranslationKey,
  values?: TranslationValues,
): string {
  const template = readPath(translations[locale], key) ?? readPath(translations.en, key) ?? key;
  if (!values) return template;

  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (token, name: string) => {
    const value = values[name];
    return value === undefined ? token : String(value);
  });
}

