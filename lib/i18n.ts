function matchLocale(value: unknown): Locale | null {
  if (typeof value !== "string") return null;

  const normalized = value.trim().replaceAll("_", "-").toLowerCase();
  if (!normalized) return null;

  if (normalized === "en" || normalized.startsWith("en-")) return "en";
  if (normalized === "ms" || normalized === "bm" || normalized.startsWith("ms-")) return "ms";
  if (
    normalized === "zh" ||
    normalized === "cmn" ||
    normalized === "zh-cn" ||
    normalized === "zh-sg" ||
    normalized.startsWith("zh-hans") ||
    normalized.startsWith("cmn-")
  ) {
    return "zh-CN";
  }
  if (
    normalized === "yue" ||
    normalized.startsWith("yue-") ||
    normalized === "zh-hk" ||
    normalized === "zh-mo" ||
    normalized === "zh-tw" ||
    normalized.startsWith("zh-hant")
  ) {
    return "yue";
  }
  if (normalized === "ta" || normalized.startsWith("ta-")) return "ta";

  return null;
}

export function isLocale(value: unknown): value is Locale {
  return typeof value === "string" && LOCALES.includes(value as Locale);
}

/** Safely accepts stored values, browser language tags, and API input. */
export function parseLocale(value: unknown, fallback: Locale = DEFAULT_LOCALE): Locale {
  return matchLocale(value) ?? fallback;
}

